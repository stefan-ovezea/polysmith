bool expect(bool condition, const char* message) {
  if (condition) return true;
  std::cerr << message << "\n";
  return false;
}

SketchFeatureParameters sketch_params(const DocumentState& document) {
  for (const auto& feature : document.feature_history) {
    if (feature.kind == "sketch" && feature.sketch_parameters.has_value()) {
      return feature.sketch_parameters.value();
    }
  }
  throw std::runtime_error("no sketch feature in document");
}

// The one text entity in the sketch (tests add exactly one).
const SketchText& only_text(const SketchFeatureParameters& params) {
  if (params.texts.size() != 1) {
    throw std::runtime_error("expected exactly one sketch text");
  }
  return params.texts[0];
}

std::vector<std::string> generated_line_ids(
    const SketchFeatureParameters& params) {
  std::vector<std::string> ids;
  for (const auto& line : params.lines) {
    if (line.generated_by.has_value()) {
      ids.push_back(line.id);
    }
  }
  return ids;
}

// One closed glyph contour becomes exactly one profile region (outer
// or hole). The expected region count is derived from the engine's own
// contour count for the same string, so the assertion holds for any
// resolved font (DejaVu, Arial, a future bundled font, ...).
int expected_contour_count(const std::string& utf8_text,
                           double height_mm) {
  polysmith::core::text::TextLayout layout;
  std::string error;
  const polysmith::core::text::TextStyle style{
      /*font_path=*/"", height_mm};
  if (!polysmith::core::text::TextEngine::instance().layout(
          utf8_text, 0.0, 0.0, style, &layout, &error)) {
    return -1;
  }
  return static_cast<int>(layout.contours.size());
}

bool test_text_o_profiles() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  SketchText text;
  text.text = "O";
  text.height_mm = 20.0;
  DocumentState document = manager.add_sketch_text(text);
  const auto params = sketch_params(document);

  // Every glyph segment is generated by the text entity.
  const auto generated = generated_line_ids(params);
  if (!expect(!generated.empty(), "O: glyph segments exist")) return false;
  for (const auto& line : params.lines) {
    if (!expect(line.generated_by.has_value() &&
                    line.generated_by.value() == "text:text-1",
                "O: every line is generated by text-1")) {
      return false;
    }
    if (!expect(!line.constraint.has_value(),
                "O: glyph lines carry no constraints")) {
      return false;
    }
  }

  // Exactly two regions: the outer ring and the hole (O has one hole
  // in every resolved font; the count is still derived from the engine
  // so the assertion survives font changes). Build the expected sets
  // from the document itself (the tessellation count is font-dependent)
  // and assert the complete set plus the nesting.
  const int expected_rings = expected_contour_count("O", 20.0);
  if (!expect(expected_rings > 0 && static_cast<int>(params.profiles.size()) ==
                                       expected_rings,
              "O: exactly 2 profiles (outer ring + hole)")) {
    return false;
  }
  std::vector<polysmith::test::ExpectedProfile> expected;
  for (const auto& profile : params.profiles) {
    if (!expect(profile.kind == "polygon" && !profile.source_circle_id,
                "O: both regions are polygon profiles without source circle")) {
      return false;
    }
    expected.push_back({.entity_ids = profile.line_ids,
                        .kind = "polygon",
                        .has_source_circle_id = false});
  }
  std::string reason;
  if (!expect(polysmith::test::profiles_match(document, expected, &reason),
              ("O: complete region set: " + reason).c_str())) {
    return false;
  }

  // Nesting: the outer region lists the hole as an inner loop, the hole
  // lists none. The union of both region id sets is the full glyph set.
  int with_inner = 0;
  std::vector<std::string> union_ids;
  for (const auto& profile : params.profiles) {
    if (!profile.inner_loops.empty()) ++with_inner;
    union_ids.insert(union_ids.end(), profile.line_ids.begin(),
                     profile.line_ids.end());
  }
  if (!expect(with_inner == 1,
              "O: exactly one region carries an inner loop (the hole)")) {
    return false;
  }
  std::sort(union_ids.begin(), union_ids.end());
  auto sorted_generated = generated;
  std::sort(sorted_generated.begin(), sorted_generated.end());
  if (!expect(union_ids == sorted_generated,
              "O: profile regions cover exactly the generated glyph set")) {
    return false;
  }

  // Glyph vertices are fixed; the DOF counter reports generated lines
  // as fully constrained so the viewport renders them in the fixed color.
  for (const auto& vertex : params.vertices) {
    if (vertex.id.rfind("vertex-text-", 0) == 0) {
      if (!expect(vertex.is_fixed, "O: glyph vertices are fixed")) {
        return false;
      }
    }
  }
  if (!expect(polysmith::core::get_entity_dof_status(params, generated[0]) ==
                  DofStatus::FullyConstrained,
              "O: generated lines report fully constrained")) {
    return false;
  }
  return true;
}

bool test_text_ab_profiles() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  SketchText text;
  text.text = "AB";
  text.height_mm = 10.0;
  DocumentState document = manager.add_sketch_text(text);
  const auto params = sketch_params(document);

  // Every glyph contour (outer + holes) becomes exactly one profile
  // region — e.g. DejaVu/Arial: A = outer + 1 hole, B = outer + 2
  // holes → 5 regions. None carry source circles; the outer regions
  // nest their holes.
  const int expected = expected_contour_count("AB", 10.0);
  if (!expect(expected > 0, "AB: engine layout succeeds")) {
    return false;
  }
  if (!expect(static_cast<int>(params.profiles.size()) == expected,
              "AB: one profile region per glyph contour")) {
    return false;
  }
  std::vector<polysmith::test::ExpectedProfile> expected_profiles;
  int with_inner = 0;
  for (const auto& profile : params.profiles) {
    expected_profiles.push_back({.entity_ids = profile.line_ids,
                                 .kind = "polygon",
                                 .has_source_circle_id = false});
    if (!profile.inner_loops.empty()) ++with_inner;
  }
  if (!expect(with_inner >= 1,
              "AB: outer regions nest their holes")) {
    return false;
  }
  std::string reason;
  return expect(
      polysmith::test::profiles_match(document, expected_profiles, &reason),
      ("AB: complete region set: " + reason).c_str());
}

bool test_reexpansion_stability() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  SketchText text;
  text.text = "OK";
  text.height_mm = 12.0;
  DocumentState document = manager.add_sketch_text(text);
  const auto before = sketch_params(document);

  // No-op update with identical values: expansion must reproduce the
  // exact same ids and coordinates (deterministic re-derivation).
  document = manager.update_sketch_text(only_text(before).id, before.texts[0]);
  const auto after = sketch_params(document);

  if (!expect(before.lines.size() == after.lines.size(),
              "stability: segment count unchanged")) {
    return false;
  }
  for (size_t i = 0; i < before.lines.size(); ++i) {
    if (!expect(before.lines[i].id == after.lines[i].id &&
                    before.lines[i].start_vertex_id ==
                        after.lines[i].start_vertex_id &&
                    before.lines[i].end_vertex_id ==
                        after.lines[i].end_vertex_id,
                "stability: ids identical across re-expansion")) {
      return false;
    }
    if (!expect(std::abs(before.lines[i].start_x - after.lines[i].start_x) <
                        1e-9 &&
                    std::abs(before.lines[i].start_y - after.lines[i].start_y) <
                        1e-9 &&
                    std::abs(before.lines[i].end_x - after.lines[i].end_x) <
                        1e-9 &&
                    std::abs(before.lines[i].end_y - after.lines[i].end_y) <
                        1e-9,
                "stability: coordinates identical across re-expansion")) {
      return false;
    }
  }
  return true;
}

bool test_height_edit_keeps_ids_and_scales() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  SketchText text;
  text.text = "O";
  text.height_mm = 20.0;
  DocumentState document = manager.add_sketch_text(text);
  const auto before = sketch_params(document);

  // Height edit scales glyphs 1.5x. The tolerance is proportional to
  // the height, so the tessellation structure — and therefore the
  // generated id set — is unchanged (the TNP contract: profile ids
  // survive, linked extrudes re-snapshot instead of breaking).
  SketchText updated = before.texts[0];
  updated.height_mm = 30.0;
  document = manager.update_sketch_text(updated.id, updated);
  const auto after = sketch_params(document);

  if (!expect(before.lines.size() == after.lines.size(),
              "height: segment count unchanged")) {
    return false;
  }
  for (size_t i = 0; i < before.lines.size(); ++i) {
    if (!expect(before.lines[i].id == after.lines[i].id,
                "height: generated ids unchanged")) {
      return false;
    }
    const double scale = 30.0 / 20.0;
    if (!expect(std::abs(after.lines[i].start_x -
                         before.lines[i].start_x * scale) < 1e-6 &&
                    std::abs(after.lines[i].start_y -
                         before.lines[i].start_y * scale) < 1e-6,
                "height: coordinates scale by exactly 1.5")) {
      return false;
    }
  }

  // Profile ids embed corner coordinates, so they intentionally change
  // under any geometric edit. The TNP-relevant property is the line-id
  // SET: identical generated ids keep every region bounded by the same
  // line set, which is what find_equivalent_profile's containment
  // fallback matches on when re-snapshotting linked extrudes.
  for (const auto& profile : before.profiles) {
    std::set<std::string> want(profile.line_ids.begin(),
                               profile.line_ids.end());
    const auto found = std::find_if(
        after.profiles.begin(), after.profiles.end(),
        [&](const auto& p) {
          std::set<std::string> have(p.line_ids.begin(), p.line_ids.end());
          return have == want;
        });
    if (!expect(found != after.profiles.end(),
                "height: region line-id sets survive the edit")) {
      return false;
    }
  }
  return true;
}

