bool test_degenerate_strings() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  // Empty and whitespace-only strings render no geometry — the text
  // record persists so the user can type into it, and nothing crashes.
  SketchText text;
  text.text = "   ";
  DocumentState document = manager.add_sketch_text(text);
  auto params = sketch_params(document);
  if (!expect(params.texts.size() == 1 &&
                  generated_line_ids(params).empty(),
              "degenerate: whitespace-only text generates no geometry")) {
    return false;
  }
  if (!expect(params.profiles.empty(),
              "degenerate: no profiles from empty glyphs")) {
    return false;
  }

  SketchText updated = params.texts[0];
  updated.text = "OK";
  document = manager.update_sketch_text(updated.id, updated);
  params = sketch_params(document);
  return expect(!generated_line_ids(params).empty(),
                "degenerate: typing real text after empty string works");
}

bool test_char_limit() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  SketchText text;
  text.text = std::string(501, 'X');
  bool threw = false;
  try {
    manager.add_sketch_text(text);
  } catch (const std::runtime_error&) {
    threw = true;
  }
  if (!expect(threw, "cap: 501 characters is rejected")) {
    return false;
  }

  // The failed add must not leave a half-created text or geometry.
  const auto params = sketch_params(manager.get_document().value());
  return expect(params.texts.empty() && generated_line_ids(params).empty(),
                "cap: rejected add leaves the sketch untouched");
}

bool test_undo_restores_text() {
  DocumentManager manager;
  manager.create_document();
  manager.start_sketch_on_plane("ref-plane-xy");

  SketchText text;
  text.text = "O";
  text.height_mm = 10.0;
  DocumentState document = manager.add_sketch_text(text);
  const auto with_text = sketch_params(document);

  document = manager.undo();
  const auto undone = sketch_params(document);
  if (!expect(undone.texts.empty() && generated_line_ids(undone).empty(),
              "undo: text and glyph lines gone")) {
    return false;
  }

  document = manager.redo();
  const auto redone = sketch_params(document);
  if (!expect(redone.texts.size() == 1 &&
                  redone.lines.size() == with_text.lines.size(),
              "redo: text and glyph lines restored")) {
    return false;
  }
  return expect(redone.texts[0].id == with_text.texts[0].id &&
                    redone.lines[0].id == with_text.lines[0].id,
                "redo: ids restored exactly");
}

